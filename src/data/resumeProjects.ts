/** 프로젝트 하나를 자소서에 붙여 넣기 좋은 일반 텍스트로 변환 */
export const formatProjectText = (p: ProjectStructure): string => {
  const risks = p.risksAndSolutions
    .map((r, i) => {
      const lines = [`  [위험 ${i + 1}] ${r.risk}`];
      if (r.cause) lines.push(`   - 원인: ${r.cause}`);
      lines.push(`   ➔ 해결: ${r.solution}`);
      if (r.result) lines.push(`   ✓ 결과: ${r.result}`);
      return lines.join('\n');
    })
    .join('\n');

  return [
    `[${p.title}]`,
    `기간: ${p.period}`,
    `역할: ${p.role}`,
    `기술: ${p.stack.join(', ')}`,
    `핵심 수치: ${p.highlights.map((h) => `${h.label} ${h.value}`).join(' · ')}`,
    '',
    '1. 계기',
    p.motivation,
    '',
    '2. 요약',
    p.summary,
    ...p.summaryPoints.map((s) => ` - ${s}`),
    '',
    '3. 위험상황 및 해결한 방법',
    risks,
    '',
    '4. 한계',
    ...p.limitations.map((l) => ` - ${l}`),
  ].join('\n');
};
