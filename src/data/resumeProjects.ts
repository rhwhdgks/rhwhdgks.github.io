/** 프로젝트에 붙은 역량 전체 (사례 태그 + 사례 밖 역량), 중복 제거 */
export const projectCompetencies = (p: ProjectStructure): CompetencyId[] => {
  const all = [...p.risksAndSolutions.flatMap((r) => r.competencies), ...(p.extraCompetencies || [])];
  return all.filter((c, i) => all.indexOf(c) === i);
};

export const competencyLabels = (ids: CompetencyId[]): string => ids.map((c) => COMPETENCIES[c].label).join(', ');

export const getTrack = (id: TrackId) => JOB_TRACKS.find((t) => t.id === id)!;

/** 지원 직무 기준 프로젝트 순서 (직무 미선택이면 기본 순서) */
export const orderedProjects = (trackId: TrackId | null): ProjectStructure[] => {
  if (!trackId) return PROJECTS_STRUCTURED;
  const order = getTrack(trackId).order;
  return [...PROJECTS_STRUCTURED].sort((a, b) => order.indexOf(a.id) - order.indexOf(b.id));
};

/** 프로젝트 하나를 자소서에 붙여 넣기 좋은 일반 텍스트로 변환 (직무를 고르면 그 직무의 강조점 포함) */
export const formatProjectText = (p: ProjectStructure, trackId: TrackId | null = null): string => {
  const risks = p.risksAndSolutions
    .map((r, i) => {
      const lines = [`  [위험 ${i + 1}] ${r.risk} (역량: ${competencyLabels(r.competencies)})`];
      if (r.cause) lines.push(`   - 원인: ${r.cause}`);
      lines.push(`   ➔ 해결: ${r.solution}`);
      if (r.result) lines.push(`   ✓ 결과: ${r.result}`);
      return lines.join('\n');
    })
    .join('\n');

  const qas = p.interviewQA
    .map((qa, i) => `  [Q${i + 1}] ${qa.q}\n   ➔ A: ${qa.a}`)
    .join('\n');

  return [
    `[${p.title}]`,
    `포트폴리오 1줄 요약: ${p.portfolio.headline}`,
    `기간: ${p.period}`,
    `역할: ${p.role}`,
    `기술: ${p.stack.join(', ')}`,
    `핵심 수치: ${p.highlights.map((h) => `${h.label} ${h.value}`).join(' · ')}`,
    `역량: ${competencyLabels(projectCompetencies(p))}`,
    ...(trackId ? [`${getTrack(trackId).label} 지원 시 강조: ${p.trackFocus[trackId]}`] : []),
    '',
    '30초 요약',
    p.pitch30,
    '',
    '2분 설명',
    ...p.pitch2min,
    '',
    '1. 계기',
    p.motivation,
    '',
    '2. 요약',
    p.summary,
    ...p.summaryPoints.map((s) => ` - ${s}`),
    '',
    '3. 위험상황 및 해결한 방법',
    risks,
    '',
    '4. 한계',
    ...p.limitations.map((l) => ` - ${l}`),
    '',
    '5. 예상 꼬리질문 & 방어 답변',
    qas,
  ].join('\n');
};
